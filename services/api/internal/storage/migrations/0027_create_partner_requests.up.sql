CREATE TABLE partner_requests
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_user_id BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    to_user_id   BIGINT      NOT NULL REFERENCES users (user_id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT partner_requests_pair_key UNIQUE (from_user_id, to_user_id)
);

CREATE INDEX idx_partner_requests_to_user_id ON partner_requests (to_user_id);
